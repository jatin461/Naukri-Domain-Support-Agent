"""Builds the acceptance pass/fail matrix from EXECUTED tests only.

Usage: .venv/bin/python -m scripts.acceptance_report [junit.xml]
Reads the JUnit XML written by `pytest --junitxml` (tests carry their criterion IDs through `@pytest.mark.ac("P1-01")`,
copied into the XML by tests/conftest.py) and the criterion list in docs/requirements_traceability.md.
A criterion is PASS only if at least one test tagged with it ran and every tagged test passed; a criterion with no executed
test is reported NOT EXECUTED and is never counted as passed. S-01 (publishing the public repository) needs the repository owner.
Exit code 1 if any criterion failed or was not executed, except the documented manual one.
"""
import re
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TRACE = ROOT / "docs" / "requirements_traceability.md"
DEFAULT_XML = ROOT / ".acceptance" / "junit.xml"
OUT = ROOT / "evaluation" / "reports" / "acceptance_matrix.md"
MANUAL = {"S-01": "needs the repository owner: publish the repository on GitHub as public (this tool never pushes)"}


def criteria():
    """[(id, description)] for the 68 checklist criteria (P1..P4, S) and the 32 extra requirements (X)."""
    rows = []
    for line in TRACE.read_text(encoding="utf-8").splitlines():
        m = re.match(r"\| ((?:P[1-4]|S|X)-\d\d) \| (.*?) \|", line)
        if m:
            rows.append((m.group(1), m.group(2)))
    return rows


def executed_results(xml_path):
    results = defaultdict(list)  # id -> [(test name, outcome)]
    for case in ET.parse(xml_path).getroot().iter("testcase"):
        outcome = "passed"
        if case.find("failure") is not None or case.find("error") is not None:
            outcome = "failed"
        elif case.find("skipped") is not None:
            outcome = "skipped"
        name = f"{case.get('classname', '')}::{case.get('name')}".lstrip(":")
        for prop in case.iter("property"):
            if prop.get("name") == "ac":
                results[prop.get("value")].append((name, outcome))
    return results


def build(xml_path=DEFAULT_XML):
    res = executed_results(xml_path)
    rows = []
    for cid, desc in criteria():
        tests = res.get(cid, [])
        if not tests:
            status = "NOT EXECUTED"
        elif all(o == "passed" for _, o in tests):
            status = "PASS"
        else:
            status = "FAIL"
        rows.append({"id": cid, "description": desc, "status": status, "tests": tests})
    return rows


def render(rows):
    total = len(rows)
    counts = {s: sum(r["status"] == s for r in rows) for s in ("PASS", "FAIL", "NOT EXECUTED")}
    part = lambda prefix: [r for r in rows if r["id"].startswith(prefix)]
    L = ["# Acceptance matrix (generated from executed tests)", "",
         "Generated by `scripts/acceptance_report.py` from the JUnit report of `pytest`. A criterion is PASS only when at least one test tagged with it ran and all tagged tests passed. "
         "No criterion is marked passed without an executed test.", "",
         f"Totals: {counts['PASS']} PASS, {counts['FAIL']} FAIL, {counts['NOT EXECUTED']} NOT EXECUTED of {total} criteria.", "",
         "| Group | Criteria | PASS |", "|---|---|---|"]
    for label, prefix in (("Part 1", "P1-"), ("Part 2", "P2-"), ("Part 3", "P3-"), ("Part 4", "P4-"), ("Submission", "S-"), ("Extra requirements", "X-")):
        g = part(prefix)
        L.append(f"| {label} | {len(g)} | {sum(r['status'] == 'PASS' for r in g)} |")
    L += ["", "| ID | Status | Executed tests | Criterion |", "|---|---|---|---|"]
    for r in rows:
        tests = "<br>".join(f"`{n.split('::', 1)[-1]}` ({o})" for n, o in r["tests"]) or (MANUAL.get(r["id"]) or "no executed test")
        L.append(f"| {r['id']} | {r['status']} | {tests} | {r['description'][:140].replace('|', '/')} |")
    return "\n".join(L) + "\n"


def main():
    xml = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_XML
    rows = build(xml)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(rows), encoding="utf-8")
    bad = [r for r in rows if r["status"] != "PASS" and r["id"] not in MANUAL]
    print(f"{sum(r['status'] == 'PASS' for r in rows)}/{len(rows)} criteria PASS; matrix written to {OUT.relative_to(ROOT)}")
    for r in bad:
        print(f"  {r['status']}: {r['id']}")
    for cid, why in MANUAL.items():
        print(f"  MANUAL: {cid} {why}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
